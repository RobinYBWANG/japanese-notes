# read_fix.py —— 合成前的讀音修正（export_missing_clips.py、mock_audio.py 共用）
#
# clip 的 key 仍是原文（前端拿原文查 clip），只有「送給引擎的文字」換掉。
# 每一條都是 2026-10-24 全站讀音稽核實際抓到引擎念錯的（audio_query 的 mora 對照正確讀音）。
# 規則依序套用；正規表示式。
import re

READ_FIX = [
    (r'中は 何ですか', 'なかは なんですか'),   # 引擎念 ちゅうは
    (r'何ですか', 'なんですか'),                # 引擎念 なにですか
    (r'何の', 'なんの'),
    (r'日本語', 'にほんご'),                    # 要排在「日本」前面，不然會變成「にほん語」
    (r'日本', 'にほん'),                        # 引擎預設唸 ニッポン，課本教的是 にほん
    (r'林さん', 'りんさん'),                    # 課本的林さん是中國人（りん），引擎預設念 はやしさん
    (r'あの方', 'あのかた'),                    # 引擎念 あのほう
    (r'夜市', 'よいち'),                        # 引擎念 やじ
    (r'中秋節', 'ちゅうしゅうせつ'),            # 引擎念 ちゅうしゅうぶし
    (r'辛い', 'からい'),                        # 引擎念 つらい
    (r'高い山', 'たかい やま'),                 # 引擎念 たかいざん
    (r'二十歳', 'はたち'),                      # 引擎念 にじゅっさい
    (r'米は', 'こめは'),                        # 引擎念 べい
    (r'(雨|雪)が 降', r'\1が ふ'),              # 引擎念 おります（下車）
    (r'^歳$', 'さい'),                          # 單字「歳」單獨念會變 とし
    (r'^語$', 'ご'),                            # 單字「語」單獨念會變 かたり
    (r'かれは ', 'かれわ '),                    # 引擎把這個 は 念成 ha
    (r'^はは$', 'ハハ'),                        # 引擎念 わわ
    (r'じょうは(?=[\s　、])', 'じょうわ'),        # 「ちゅうしゃじょうは」的助詞 は 引擎念 ha
    (r'(^|[\s　、])はこ', r'\1ハコ'),          # 詞首的 はこ（箱）前面接「〜は」時引擎念 わこ
    (r'はち', 'ハチ'),                          # 引擎常把 はち 念成 わち（はち、じゅうはち、はちがつ、れいてんはちさん）
    (r'さつ(?=$|[\s　、。])', 'サツ'),           # 詞尾的 さつ 引擎念 さっ（さつ、なんさつ、にさつ あります）
]


def engine_text(t):
    for a, b in READ_FIX:
        t = re.sub(a, b, t)
    return t

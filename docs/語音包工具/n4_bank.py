def V(q, c, e, a=0, **kw):
    return dict(q=q, c=c, a=a, e=e, **kw)


def R(pas, zh, items):
    """讀解：一篇文章配幾題"""
    return [dict(it, **{'pass': pas, 'passZh': zh}) for it in items]


def L(*lines):
    """聴解台詞：('F'|'M'|'N', 文字)"""
    return [{'r': r, 't': t} for r, t in lines]


def PIC(n, q, lines, zh, ans, e):
    """課題理解：四格圖，ans = 正解格號（1〜4）"""
    return dict(audio=L(*lines), audioZh=zh, img='img/mock/n4-l1-%02d.png' % n, fixed=True,
                q=q, c=['1', '2', '3', '4'], a=ans - 1, e=e)


def SAY(n, narr, zh, c, e):
    """発話表現：場景圖＋旁白，選項只唸不顯示"""
    return dict(scene={'img': 'img/mock/n4-l3-%02d.png' % n}, audio=L(('N', narr)), readChoices=True,
                audioZh=zh, q='何と 言いますか。', c=c, a=0, e=e)


def RES(r, t, zh, c, e):
    """即時応答"""
    return dict(audio=L((r, t)), readChoices=True, audioZh=zh, q='（へんじを えらんで ください）', c=c, a=0, e=e)



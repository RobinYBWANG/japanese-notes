_KEYS = sorted(TO_KANA, key=len, reverse=True)
_TAG = re.compile(r'(<span class="ul">.*?</span>|<[^>]+>)')


def n5ify(text, keep_ul=False):
    """把表外漢字的詞改成平假名寫法。HTML 標籤不動；keep_ul=True 時，底線（漢字讀法題考的那個詞）也不動。"""
    out = []
    for part in _TAG.split(text):
        if not part or part.startswith('<'):
            if part.startswith('<span class="ul">') and not keep_ul:
                part = '<span class="ul">' + n5ify(part[17:-7]) + '</span>'
            out.append(part)
            continue
        for k in _KEYS:
            if k in part:
                part = part.replace(k, TO_KANA[k])
        out.append(part)
    return ''.join(out)
